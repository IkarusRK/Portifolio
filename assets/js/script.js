/* menu superior */
function initNav() {
  const nav = document.getElementById('nav');
  const hamburger = document.getElementById('nav-hamburger');
  const mobileMenu = document.getElementById('nav-mobile');
  const mobileLinks = mobileMenu.querySelectorAll('.nav__link');

  /* rolagem na nav */
  window.addEventListener('scroll', () => {
    nav.classList.toggle('scrolled', window.scrollY > 20);
    updateActiveLink();
  }, { passive: true });

  /* botao hamburguer */
  hamburger.addEventListener('click', () => {
    mobileMenu.classList.toggle('open');
    document.body.style.overflow = mobileMenu.classList.contains('open') ? 'hidden' : '';
  });

  mobileLinks.forEach(link => {
    link.addEventListener('click', () => {
      mobileMenu.classList.remove('open');
      document.body.style.overflow = '';
    });
  });
}

function updateActiveLink() {
  const sections = document.querySelectorAll('section[id], div[id="hero"]');
  const navLinks = document.querySelectorAll('.nav__link[data-section]');
  const scrollPos = window.scrollY + 100;

  let current = '';
  sections.forEach(section => {
    if (section.offsetTop <= scrollPos) current = section.id;
  });

  navLinks.forEach(link => {
    link.classList.toggle('active', link.dataset.section === current);
  });
}

/* troca de idioma */
function initLangSwitcher() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      applyLang(btn.dataset.lang);
    });
  });
}

function applyLang(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  const t = I18N[lang];

  /* atualiza atributo lang */
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;

  /* links da nav */
  document.querySelectorAll('.nav__link[data-i18n-nav]').forEach(el => {
    const idx = parseInt(el.dataset.i18nNav);
    el.textContent = t.nav[idx];
  });

  /* outros elementos com i18n */
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = t[key];
      } else {
        el.innerHTML = t[key];
      }
    }
  });

  /* niveis nas habilidades */
  document.querySelectorAll('[data-i18n-level]').forEach(el => {
    const levelKey = el.dataset.i18nLevel;
    el.textContent = t[levelKey] || el.textContent;
  });

  /* atualiza titulo do site */
  document.title = lang === 'pt'
    ? 'Elian Rodrigues — Desenvolvedor Backend'
    : lang === 'en'
    ? 'Elian Rodrigues — Backend Developer'
    : lang === 'es'
    ? 'Elian Rodrigues — Desarrollador Backend'
    : 'Elian Rodrigues — 后端开发者';

  /* reinicia animacao de digitacao */
  if (typedInterval) clearInterval(typedInterval);
  typedIndex = 0; charIndex = 0; isDeleting = false;
  initTyped();

  /* atualiza botao ativo */
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

/* animacao de texto digitando */
function initTyped() {
  const el = document.getElementById('typed-text');
  if (!el) return;
  const strings = I18N[currentLang].hero_typed;

  function type() {
    const current = strings[typedIndex];
    if (isDeleting) {
      el.textContent = current.substring(0, charIndex - 1);
      charIndex--;
    } else {
      el.textContent = current.substring(0, charIndex + 1);
      charIndex++;
    }

    let delay = isDeleting ? 60 : 100;
    if (!isDeleting && charIndex === current.length) {
      delay = 2000;
      isDeleting = true;
    } else if (isDeleting && charIndex === 0) {
      isDeleting = false;
      typedIndex = (typedIndex + 1) % strings.length;
      delay = 400;
    }
    typedInterval = setTimeout(type, delay);
  }
  type();
}

/* animacao de scroll */
function initScrollReveal() {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
      }
    });
  }, { threshold: 0.1, rootMargin: '0px 0px -40px 0px' });

  document.querySelectorAll('.reveal, .reveal-left, .reveal-right').forEach(el => {
    observer.observe(el);
  });
}

/* formulario de contato */
function initContactForm() {
  const form = document.getElementById('contact-form');
  if (!form) return;

  form.addEventListener('submit', (e) => {
    e.preventDefault();
    const name    = form.querySelector('#form-name').value;
    const email   = form.querySelector('#form-email').value;
    const subject = form.querySelector('#form-subject').value;
    const message = form.querySelector('#form-message').value;

    const mailto = `mailto:elianrodriguesribeiro@gmail.com`
      + `?subject=${encodeURIComponent(subject + ' — de ' + name)}`
      + `&body=${encodeURIComponent(`Nome: ${name}\nE-mail: ${email}\n\n${message}`)}`;

    window.location.href = mailto;

    /* msg de sucesso */
    form.style.opacity = '0';
    form.style.transform = 'translateY(-10px)';
    form.style.transition = '0.4s ease';
    setTimeout(() => {
      form.style.display = 'none';
      const success = document.getElementById('form-success');
      if (success) {
        success.style.display = 'block';
        success.style.opacity = '0';
        setTimeout(() => { success.style.opacity = '1'; success.style.transition = '0.4s ease'; }, 50);
      }
    }, 400);
  });
}
